// Generates typed analytics helpers from events.yaml.
//   node gen.mjs          write generated/
//   node gen.mjs --check  fail if generated/ is stale
// Swift and Kotlin get client and web events only (the apps cannot send server events).
// TypeScript and Python get every event.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const TYPES = new Set(["token", "did", "int", "int64", "number", "bool", "enum", "uuid"]);
const SOURCES = new Set(["client", "web", "server"]);

const camel = (s) => s.replace(/_(\w)/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
const screaming = (s) => s.toUpperCase();

export function loadSpec(file = join(here, "events.yaml")) {
  const raw = parse(readFileSync(file, "utf8"));
  const { forbidden, common_props: common = {}, envelope, events } = raw;
  const names = new Set(forbidden.names);
  const check = (where, name, p) => {
    if (!/^[a-z][a-z0-9_]*$/.test(name)) throw new Error(`${where}: bad name ${name}`);
    if (names.has(name) || forbidden.name_contains.some((s) => name.includes(s)))
      throw new Error(`${where}: property "${name}" is forbidden (${forbidden.rule.trim()})`);
    if (!TYPES.has(p.type)) throw new Error(`${where}.${name}: unknown type ${p.type}`);
    if (p.type === "enum" && !(p.values?.length > 0 && p.values.every((v) => /^[a-z][a-z0-9_]*$/.test(v))))
      throw new Error(`${where}.${name}: enum needs snake_case values`);
  };
  for (const [n, p] of Object.entries(common)) check("common_props", n, p);
  for (const [n, p] of Object.entries(envelope)) {
    if (!TYPES.has(p.type)) throw new Error(`envelope.${n}: unknown type`);
  }
  for (const [ev, def] of Object.entries(events)) {
    if (!/^[a-z][a-z0-9_]{0,39}$/.test(ev)) throw new Error(`event ${ev}: GA4 allows 40 chars of [a-z0-9_]`);
    if (!SOURCES.has(def.source)) throw new Error(`event ${ev}: bad source`);
    def.props ??= {};
    const props = Object.entries(def.props);
    if (props.length + Object.keys(common).length > 25) throw new Error(`event ${ev}: GA4 allows 25 params`);
    for (const [n, p] of props) {
      check(`event ${ev}`, n, p);
      if (n in common) throw new Error(`event ${ev}: ${n} is a common prop`);
    }
  }
  return { version: raw.version, forbidden, common, envelope, events };
}

// Enum type name: the property name when every use agrees on the values, else event + property.
function enumNames(events) {
  const seen = {};
  for (const [ev, def] of Object.entries(events))
    for (const [n, p] of Object.entries(def.props))
      if (p.type === "enum") (seen[n] ??= new Set()).add(p.values.join(","));
  const nameOf = (ev, n) => (seen[n].size === 1 ? pascal(n) : pascal(ev) + pascal(n));
  const defs = new Map();
  for (const [ev, def] of Object.entries(events))
    for (const [n, p] of Object.entries(def.props))
      if (p.type === "enum") defs.set(nameOf(ev, n), p.values);
  return { nameOf, defs };
}

const clientOnly = (events) => Object.fromEntries(Object.entries(events).filter(([, d]) => d.source !== "server"));
const HEADER = "Generated by account/analytics/gen.mjs from events.yaml. Do not edit.";

function swift(spec) {
  const events = clientOnly(spec.events);
  const { nameOf, defs } = enumNames(events);
  const T = { token: "String", did: "String", int: "Int", number: "Double", bool: "Bool" };
  const V = { token: ".string", did: ".string", int: ".int", number: ".double", bool: ".bool" };
  let o = `// ${HEADER}\n// Only client and web events exist here: the app cannot name a server event or an undeclared property.\n\n`;
  o += `public enum AnalyticsValue: Sendable, Equatable {\n    case string(String), int(Int), double(Double), bool(Bool)\n}\n\n`;
  o += `public struct AnalyticsEvent: Sendable, Equatable {\n    public let name: String\n    public let properties: [String: AnalyticsValue]\n    fileprivate init(_ name: String, _ properties: [String: AnalyticsValue]) {\n        self.name = name\n        self.properties = properties\n    }\n}\n\n`;
  o += `public enum Analytics {\n`;
  for (const [name, vals] of defs) {
    o += `    public enum ${name}: String, Sendable, CaseIterable {\n`;
    o += vals.map((v) => `        case ${camel(v)} = "${v}"`).join("\n") + "\n    }\n";
  }
  const commonArg = Object.keys(spec.common).map((n) => `${camel(n)}: String? = nil`);
  for (const [ev, def] of Object.entries(events)) {
    const args = [];
    const body = [];
    for (const [n, p] of Object.entries(def.props)) {
      const ty = p.type === "enum" ? nameOf(ev, n) : T[p.type];
      const val = p.type === "enum" ? `.string(${camel(n)}.rawValue)` : `${V[p.type]}(${camel(n)})`;
      args.push(`${camel(n)}: ${ty}${p.optional ? "? = nil" : ""}`);
      body.push(p.optional ? `        if let ${camel(n)} { p["${n}"] = ${val} }` : `        p["${n}"] = ${val}`);
    }
    for (const n of Object.keys(spec.common)) body.push(`        if let ${camel(n)} { p["${n}"] = .string(${camel(n)}) }`);
    o += `\n    public static func ${camel(ev)}(${[...args, ...commonArg].join(", ")}) -> AnalyticsEvent {\n        var p: [String: AnalyticsValue] = [:]\n${body.join("\n")}\n        return AnalyticsEvent("${ev}", p)\n    }\n`;
  }
  return o + "}\n";
}

function kotlin(spec) {
  const events = clientOnly(spec.events);
  const { nameOf, defs } = enumNames(events);
  const T = { token: "String", did: "String", int: "Int", number: "Double", bool: "Boolean" };
  let o = `// ${HEADER}\n// Only client and web events exist here: the app cannot name a server event or an undeclared property.\npackage org.openentity.analytics\n\n`;
  o += `class AnalyticsEvent internal constructor(val name: String, val properties: Map<String, Any>)\n\nobject Analytics {\n`;
  for (const [name, vals] of defs)
    o += `    enum class ${name}(val wire: String) { ${vals.map((v) => `${screaming(v)}("${v}")`).join(", ")} }\n`;
  const commonArg = Object.keys(spec.common).map((n) => `${camel(n)}: String? = null`);
  for (const [ev, def] of Object.entries(events)) {
    const args = [];
    const body = [];
    for (const [n, p] of Object.entries(def.props)) {
      const ty = p.type === "enum" ? nameOf(ev, n) : T[p.type];
      const val = p.type === "enum" ? `${camel(n)}.wire` : camel(n);
      args.push(`${camel(n)}: ${ty}${p.optional ? "? = null" : ""}`);
      body.push(p.optional ? `        ${camel(n)}?.let { p["${n}"] = ${p.type === "enum" ? `it.wire` : "it"} }` : `        p["${n}"] = ${val}`);
    }
    for (const n of Object.keys(spec.common)) body.push(`        ${camel(n)}?.let { p["${n}"] = it }`);
    o += `\n    fun ${camel(ev)}(${[...args, ...commonArg].join(", ")}): AnalyticsEvent {\n        val p = mutableMapOf<String, Any>()\n${body.join("\n")}\n        return AnalyticsEvent("${ev}", p)\n    }\n`;
  }
  return o + "}\n";
}

function ts(spec) {
  const events = spec.events;
  const { nameOf, defs } = enumNames(events);
  const T = { token: "string", did: "string", int: "number", number: "number", bool: "boolean" };
  let o = `// ${HEADER}\n\nexport const SCHEMA = ${JSON.stringify({ version: spec.version, envelope: spec.envelope, common: spec.common, forbidden: spec.forbidden, events }, null, 2)} as const;\n\n`;
  o += `export type EventName = keyof typeof SCHEMA.events;\nexport type Source = "client" | "web" | "server";\n`;
  o += `declare const sealed: unique symbol;\n/** Only the helpers below can make one. */\nexport type AnalyticsEvent = { readonly name: EventName; readonly source: Source; readonly props: Readonly<Record<string, string | number | boolean>>; readonly [sealed]: true };\n`;
  o += `const make = (name: EventName, source: Source, props: Record<string, string | number | boolean | undefined>): AnalyticsEvent =>\n  ({ name, source, props: Object.fromEntries(Object.entries(props).filter(([, v]) => v !== undefined)) }) as unknown as AnalyticsEvent;\n\n`;
  for (const [name, vals] of defs) o += `export type ${name} = ${vals.map((v) => `"${v}"`).join(" | ")};\n`;
  const common = Object.keys(spec.common).map((n) => `${n}?: string`).join("; ");
  o += `\nexport const track = {\n`;
  for (const [ev, def] of Object.entries(events)) {
    const fields = Object.entries(def.props).map(([n, p]) => `${n}${p.optional ? "?" : ""}: ${p.type === "enum" ? nameOf(ev, n) : T[p.type]}`);
    fields.push(common);
    o += `  ${camel(ev)}: (p: { ${fields.join("; ")} }${fields.length === 1 && !Object.keys(def.props).length ? " = {}" : ""}) => make("${ev}", "${def.source}", p),\n`;
  }
  return o + "} as const;\n";
}

function python(spec) {
  const events = spec.events;
  const { nameOf, defs } = enumNames(events);
  const T = { token: "str", did: "str", int: "int", number: "float", bool: "bool" };
  const lit = (vals) => `Literal[${vals.map((v) => `"${v}"`).join(", ")}]`;
  const schema = JSON.stringify({ common: spec.common, events }, null, 2).replace(/\btrue\b/g, "True").replace(/\bfalse\b/g, "False").replace(/\bnull\b/g, "None");
  let o = `# ${HEADER}\nfrom __future__ import annotations\n\nimport math\nimport re\nfrom dataclasses import dataclass\nfrom typing import Literal, Optional\n\n`;
  o += `SCHEMA = ${schema}\n\n_TOKEN = re.compile(r"^[A-Za-z0-9_.:-]{1,64}$")\n_DID = re.compile(r"^[A-Za-z0-9_.:-]{1,256}$")\n_SEAL = object()\n\n`;
  o += `\n@dataclass(frozen=True)\nclass AnalyticsEvent:\n    """Only the helpers below can make one (the seal is module private)."""\n\n    name: str\n    source: str\n    props: dict\n    _seal: object = None\n\n    def __post_init__(self) -> None:\n        if self._seal is not _SEAL:\n            raise TypeError("build events with the generated helpers")\n\n\n`;
  o += `def _build(name: str, props: dict) -> AnalyticsEvent:\n    spec = SCHEMA["events"][name]\n    allowed = {**spec["props"], **SCHEMA["common"]}\n    out = {}\n    for k, v in props.items():\n        if v is None:\n            continue\n        if k not in allowed:\n            raise ValueError(f"{name}: undeclared property {k}")\n        t = allowed[k]\n        ok = (\n            (t["type"] == "token" and isinstance(v, str) and _TOKEN.match(v))\n            or (t["type"] == "did" and isinstance(v, str) and _DID.match(v))\n            or (t["type"] == "int" and isinstance(v, int) and not isinstance(v, bool) and 0 <= v <= 2147483647)\n            or (t["type"] == "number" and isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v))\n            or (t["type"] == "bool" and isinstance(v, bool))\n            or (t["type"] == "enum" and v in t["values"])\n        )\n        if not ok:\n            raise ValueError(f"{name}.{k}: bad value")\n        out[k] = v\n    for k, t in spec["props"].items():\n        if k not in out and not t.get("optional"):\n            raise ValueError(f"{name}: missing {k}")\n    return AnalyticsEvent(name, spec["source"], out, _SEAL)\n\n\n`;
  for (const [name, vals] of defs) o += `${name} = ${lit(vals)}\n`;
  for (const [ev, def] of Object.entries(events)) {
    const req = [], opt = [];
    for (const [n, p] of Object.entries(def.props)) {
      const ty = p.type === "enum" ? nameOf(ev, n) : T[p.type];
      (p.optional ? opt : req).push(p.optional ? `${n}: Optional[${ty}] = None` : `${n}: ${ty}`);
    }
    for (const n of Object.keys(spec.common)) opt.push(`${n}: Optional[str] = None`);
    const all = [...req, ...opt];
    const names = [...Object.keys(def.props), ...Object.keys(spec.common)];
    o += `\n\ndef ${ev}(${all.length ? "*, " + all.join(", ") : ""}) -> AnalyticsEvent:\n    return _build("${ev}", {${names.map((n) => `"${n}": ${n}`).join(", ")}})\n`;
  }
  return o;
}

export function render() {
  const spec = loadSpec();
  return {
    "generated/swift/Analytics.swift": swift(spec),
    "generated/kotlin/Analytics.kt": kotlin(spec),
    "generated/ts/events.ts": ts(spec),
    "generated/python/openentity_analytics.py": python(spec),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  let stale = false;
  for (const [f, text] of Object.entries(out)) {
    const p = join(here, f);
    if (process.argv.includes("--check")) {
      if (!existsSync(p) || readFileSync(p, "utf8") !== text) { console.error(`stale: ${f}`); stale = true; }
    } else {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, text);
    }
  }
  if (stale) process.exit(1);
}
