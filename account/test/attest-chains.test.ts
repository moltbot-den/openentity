test("gate lead: an issuer that is not a CA, or a CA without keyCertSign, signs nothing in a chain", () => {
  const k = () => generateKeyPairSync("ec", { namedCurve: "P-256" });
  const root = k(), mid = k(), leaf = k();
  const rootCert = new X509Certificate(testCert({ subject: "Root", issuer: "Root", key: root.publicKey, signer: root.privateKey, ca: true }));
  const leafDer = testCert({ subject: "Leaf", issuer: "Mid", key: leaf.publicKey, signer: mid.privateKey });
  const hex = (h: string) => Buffer.from(h, "hex");
  const caOnly = hex("300f0603551d130101ff040530030101ff"); // basicConstraints CA, no keyUsage
  const signOnly = hex("300e0603551d0f0101ff040403020780"); // keyUsage digitalSignature only
  const at = new Date();
  const chain = (mid: Buffer) => [new Uint8Array(leafDer), new Uint8Array(mid)];
  const midAs = (o: { ca?: boolean; extensions?: Buffer[] }) => testCert({ subject: "Mid", issuer: "Root", key: mid.publicKey, signer: root.privateKey, ...o });
  expect(chainTo(chain(midAs({ ca: true })), [rootCert], at).subject).toContain("Leaf"); // a proper CA
  expect(() => chainTo(chain(midAs({})), [rootCert], at)).toThrow(/certificate 1 is not a CA/); // a leaf-like issuer
  expect(() => chainTo(chain(midAs({ extensions: [caOnly] })), [rootCert], at)).toThrow(/certificate 1 is not a CA/); // CA, no keyUsage
  expect(() => chainTo(chain(midAs({ extensions: [caOnly, signOnly] })), [rootCert], at)).toThrow(/certificate 1 is not a CA/); // CA, no keyCertSign
});
