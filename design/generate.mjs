// tokens.json -> generated/Tokens.swift + generated/Tokens.kt. `--check` fails if the committed files are stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const dir = new URL('.', import.meta.url).pathname;
const t = JSON.parse(readFileSync(dir + 'tokens.json'));
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const rgb = (h) => h.slice(1).toUpperCase();
const colorKeys = (m) => Object.keys(t.color[m]).filter((k) => k !== 'product');
const prodKeys = Object.keys(t.color.light.product);
const HEAD = '// Generated by design/generate.mjs from design/tokens.json. Do not edit.\n';

function swift() {
  const L = [HEAD + 'import SwiftUI\n', 'enum OE {', '    // MARK: Color. Each value resolves to light or dark with the system appearance.', '    enum Color {'];
  for (const k of [...colorKeys('light'), ...prodKeys.map((p) => 'product' + cap(p))]) {
    const g = (m) => (k.startsWith('product') ? t.color[m].product[k.slice(7).toLowerCase()] : t.color[m][k]);
    L.push(`        static let ${k} = dynamic(light: 0x${rgb(g('light'))}, dark: 0x${rgb(g('dark'))})`);
  }
  L.push('', '        private static func dynamic(light: UInt32, dark: UInt32) -> SwiftUI.Color {', '            #if canImport(UIKit)', '            return SwiftUI.Color(uiColor: UIColor { $0.userInterfaceStyle == .dark ? UIColor(hex: dark) : UIColor(hex: light) })', '            #else', '            return SwiftUI.Color(hex: light)', '            #endif', '        }', '    }', '');
  L.push('    // MARK: Type. `style` scales with Dynamic Type up to AX5 when used with a Font.TextStyle.', '    struct TypeStyle { let size: CGFloat; let weight: Font.Weight; let line: CGFloat; let textStyle: Font.TextStyle; let mono: Bool', '        var font: Font { .system(textStyle, design: mono ? .monospaced : .default).weight(weight) } }', '    enum Typography {');
  const w = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' };
  const ts = { largeTitle: 'largeTitle', title: 'title', title2: 'title2', title3: 'title3', headline: 'headline', body: 'body', callout: 'callout', subheadline: 'subheadline', footnote: 'footnote', caption: 'caption' };
  for (const [k, v] of Object.entries(t.type)) if (!k.startsWith('$')) L.push(`        static let ${k} = TypeStyle(size: ${v.size}, weight: .${w[v.weight]}, line: ${v.line}, textStyle: .${ts[v.ios]}, mono: ${!!v.mono})`);
  L.push('    }', '', '    enum Space {');
  for (const [k, v] of Object.entries(t.space)) L.push(`        static let ${k}: CGFloat = ${v}`);
  L.push('    }', '', '    enum Radius {');
  for (const [k, v] of Object.entries(t.radius)) L.push(`        static let ${k}: CGFloat = ${v}`);
  L.push('    }', '', '    // MARK: Motion, in seconds. Under Reduce Motion use reduceMotionFade with a plain opacity change.', '    enum Motion {');
  for (const [k, v] of Object.entries(t.motion)) if (!k.startsWith('$')) L.push(`        static let ${k}: Double = ${v / 1000}`);
  L.push('    }', '', '    // MARK: Haptics, by event.', '    enum Haptic {', '        case ' + Object.keys(t.haptics).filter((k) => !k.startsWith('$')).join(', '), '        var ios: String {', '            switch self {');
  for (const [k, v] of Object.entries(t.haptics)) if (!k.startsWith('$')) L.push(`            case .${k}: return "${v.ios}"`);
  L.push('            }', '        }', '    }', '}', '', '#if canImport(UIKit)', 'import UIKit', 'private extension UIColor { convenience init(hex: UInt32) { self.init(red: CGFloat((hex >> 16) & 255) / 255, green: CGFloat((hex >> 8) & 255) / 255, blue: CGFloat(hex & 255) / 255, alpha: 1) } }', '#endif', 'private extension SwiftUI.Color { init(hex: UInt32) { self.init(red: Double((hex >> 16) & 255) / 255, green: Double((hex >> 8) & 255) / 255, blue: Double(hex & 255) / 255) } }', '');
  return L.join('\n');
}

function kotlin() {
  const L = [HEAD + 'package org.openentity.design\n', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', ''];
  L.push('data class OEColors(');
  const keys = [...colorKeys('light'), ...prodKeys.map((p) => 'product' + cap(p))];
  L.push(keys.map((k) => `    val ${k}: Color`).join(',\n'), ')', '');
  for (const m of ['light', 'dark']) {
    L.push(`val OE${cap(m)}Colors = OEColors(`);
    L.push(keys.map((k) => `    ${k} = Color(0xFF${rgb(k.startsWith('product') ? t.color[m].product[k.slice(7).toLowerCase()] : t.color[m][k])})`).join(',\n'), ')', '');
  }
  L.push('/** android is the Material 3 role to start from; size and weight below are the app values. */', 'data class OETypeStyle(val size: Float, val weight: Int, val line: Float, val m3Role: String, val mono: Boolean)', 'object OEType {');
  for (const [k, v] of Object.entries(t.type)) if (!k.startsWith('$')) L.push(`    val ${k} = OETypeStyle(${v.size}f, ${v.weight}, ${v.line}f, "${v.android}", ${!!v.mono})`);
  L.push('}', '', 'object OESpace {');
  for (const [k, v] of Object.entries(t.space)) L.push(`    val ${k} = ${v}.dp`);
  L.push('}', '', 'object OERadius {');
  for (const [k, v] of Object.entries(t.radius)) L.push(`    val ${k} = ${v}.dp`);
  L.push('}', '', '/** Milliseconds. Under the system animator scale of 0 use reduceMotionFade with a plain alpha change. */', 'object OEMotion {');
  for (const [k, v] of Object.entries(t.motion)) if (!k.startsWith('$')) L.push(`    const val ${k}Ms = ${v}`);
  L.push('}', '', '/** Values are HapticFeedbackConstants names. */', 'enum class OEHaptic(val android: String) {');
  L.push(Object.entries(t.haptics).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `    ${k}("${v.android}")`).join(',\n') + ';', '}', '');
  return L.join('\n');
}

const out = { 'Tokens.swift': swift(), 'Tokens.kt': kotlin() };
if (process.argv.includes('--check')) {
  for (const [f, s] of Object.entries(out)) if (readFileSync(dir + 'generated/' + f, 'utf8') !== s) { console.error(`design: generated/${f} is stale; run node design/generate.mjs`); process.exit(1); }
} else {
  mkdirSync(dir + 'generated', { recursive: true });
  for (const [f, s] of Object.entries(out)) writeFileSync(dir + 'generated/' + f, s);
}
